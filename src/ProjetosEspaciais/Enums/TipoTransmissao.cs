namespace ProjetosEspaciais.Enums;

public enum TipoTransmissao
{
    PropulsaoQuimica,         // Propulsão baseada em reações químicas (ex: foguetes de combustível líquido ou sólido)
    PropulsaoIonica,          // Propulsão baseada em ionização (ex: propulsão iônica em sondas)
    PropulsaoNuclear,         // Propulsão baseada em reações nucleares
    PropulsaoElétrica,        // Propulsão elétrica, como motores que utilizam energia solar ou outros tipos de sistemas elétricos
    TransmissaoComunicacaoRF, // Comunicação via ondas de rádio (usada para comunicação com satélites, sondas, etc.)
    TransmissaoOptica,        // Comunicação via laser ou óptica (ex: comunicação laser entre satélites)
}