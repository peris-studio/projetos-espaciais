namespace ProjetosEspaciais.Enums;

public enum TipoDocumento
{
    PlanoMissao,            // Documento que detalha os objetivos, fases e cronograma da missão.
    RelatorioCientifico,    // Relatórios com descobertas e dados científicos coletados.
    ProcedimentoOperacional,// Instruções detalhadas para operações críticas.
    EspecificacaoTecnica,   // Especificações de equipamentos, veículos e infraestrutura.
    AnaliseRisco,           // Identificação e mitigação de riscos da missão.
    DocumentoSeguranca,     // Normas e práticas de segurança da missão.
    RegistroExperimento,    // Documentação de experimentos realizados em missões espaciais.
    ManualTreinamento,      // Manuais para treinamento de astronautas e equipes técnicas.
    ContratoFornecedor,     // Acordos com empresas para fornecimento de tecnologia e serviços.
    RelatorioFalha,         // Análise detalhada de falhas e incidentes técnicos.
    DocumentoPolitica,      // Regulamentações e diretrizes institucionais.
    CertificacaoAprovacao,  // Certificações para componentes e sistemas críticos.
    RegistroComunicacao,    // Logs de comunicação entre equipes em solo e tripulações.
    DocumentoOrcamento,     // Planejamento financeiro e alocação de recursos.
    DiarioBordo             // Registro contínuo das atividades e eventos da missão.
}
