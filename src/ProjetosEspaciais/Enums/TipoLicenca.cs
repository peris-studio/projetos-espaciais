namespace ProjetosEspaciais.Enums;

public enum TipoLicenca
{
    // Licenças governamentais ou regulatórias
    LicencaLancamento,            // Licença para o lançamento de veículos espaciais
    LicencaOperacaoEspacial,      // Licença para operar veículos espaciais ou satélites
    LicencaPesquisaDesenvolvimento, // Licença para pesquisa e desenvolvimento de tecnologias espaciais
    LicencaExploracaoComercial,   // Licença para exploração comercial do espaço (ex: mineração espacial)
    LicencaComunicacoesEspaciais, // Licença para operar satélites de comunicação
    LicencaNavegacaoAerea,       // Licença relacionada a navegação aérea para espaçonaves em trajetos interplanetários

    // Licenças de conformidade com normas de segurança
    LicencaSegurancaMissao,      // Licença de segurança para missões espaciais
    LicencaConformidadeAmbiental, // Licença que garante a conformidade com regulamentos ambientais espaciais

    // Licenças para colaboração internacional
    LicencaParceriaInternacional, // Licença para colaboração internacional em projetos espaciais

    // Licenças técnicas ou de inovação
    LicencaTecnologiaAvancada,   // Licença para o uso de tecnologias inovadoras em missões espaciais
    LicencaPropriedadeIntelectual, // Licença relacionada à proteção de propriedade intelectual em projetos espaciais

    // Licenças de segurança de voo
    LicencaAprovacaoSistemaVoo,  // Licença para a aprovação do sistema de voo de uma nave espacial

    // Licenças específicas para testes
    LicencaTesteOperacional     // Licença para realização de testes operacionais de sistemas espaciais
}