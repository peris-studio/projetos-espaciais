namespace ProjetosEspaciais.Enums;

public enum TipoVeiculo
{
    Foguete,                 // Foguetes de lançamento
    Satelite,                // Satélites em órbita
    Rover,                   // Veículo de exploração (ex: rover em Marte)
    SondaEspacial,           // Sondas espaciais para exploração de planetas
    NaveEspacial,            // Naves para viagens interplanetárias
    VeiculoTransporteOrbital, // Veículos para transporte entre diferentes plataformas em órbita (ex: naves de transporte)
    VeiculoAterrissagem,     // Veículos para pouso em corpos celestes (ex: módulos de aterrissagem)
    PlataformaEspacial      // Plataformas espaciais utilizadas para experimentos ou como centros de comando
}